    "D. Targets M6 \"The user drives a van.\", H7 (earlier version) \"The user drove a "
    "sedan.\"; member \"The user's earlier car was a coupe, not a sedan.\" quoting C3 "
    "\"Correct the earlier sedan statement: that car was a coupe\": H7 correct, M6 "
    "independent, change_span C3.\n"
